#ifndef _AUCTION_MARKET_H
#define _AUCTION_MARKET_H

#include "Common.h"
#include "Policies/Singleton.h"

#include <map>
#include <unordered_map>
#include <unordered_set>
#include <vector>

struct AuctionEntry;

// Market bot: keeps the auction houses stocked from a curated catalog (world DB ahmarket_catalog / ahmarket_tier,
// generated by claude-projects/ah-market/tools/build_catalog.py) and optionally buys sensibly priced player listings.
// Runs on the world thread and changes auctions only through AuctionService.
//
// Listings are sold under random bot characters. A market listing is one with deposit 0, a random bot seller and a
// catalog item. They are taken down shortly before they expire, so unsold items are deleted instead of being mailed
// back to the bots. Each item's price drifts with what happens to the listings it posted itself: up when one sells,
// down when one goes unsold. Older bot listings (an earlier run, the old AhBot) are cleaned up the same way but teach
// it nothing.
class AuctionMarket
{
    public:
        void Load();                                        // config, catalog and price state: startup and .ahmarket reload
        void Update(uint32 diff);
        void RunAllHouses();                                // one pass over every house now (.ahmarket pass)
        std::string GetStatus() const;

    private:
        struct Tier
        {
            std::string name;
            uint32 maxListings = 0;
            uint32 minHours = 12;
            uint32 maxHours = 24;
            float spread = 0.0f;
        };

        struct CatalogItem
        {
            uint32 item = 0;
            uint32 tier = 0;
            uint32 minListings = 0;
            uint32 maxListings = 0;
            uint32 stackMin = 1;
            uint32 stackMax = 1;
            uint32 price = 0;                               // buyout per unit before drift and spread
            uint32 weight = 1;
        };

        struct Listing                                      // last seen state of one of our auctions
        {
            uint32 item = 0;
            time_t expireTime = 0;
            uint32 bid = 0;
            bool ours = false;                              // posted by this run; only these move prices
        };

        struct House
        {
            uint32 houseId = 0;                             // AuctionHouse.dbc
            uint32 team = 0;                                // ALLIANCE, HORDE or 0 for neutral
            std::map<uint32, Listing> listings;             // our auctions by id
            std::map<uint32, time_t> buyerWait;             // player auctions by id: when the buyer may decide
            uint32 spentToday = 0;
            uint32 posted = 0, sold = 0, expired = 0, cleaned = 0, bought = 0;
            std::map<uint32, uint32> tierCounts;            // as of the last pass
        };

        struct Settings
        {
            bool enabled = false;
            uint32 passInterval = 20;                       // seconds; the houses take turns
            uint32 maxPostsPerPass = 60;
            float restockChance = 0.25f;
            float soldStep = 0.05f;
            float expiredStep = 0.03f;
            float minFactor = 0.5f;
            float maxFactor = 2.0f;
            bool buyerEnabled = false;
            uint32 buyerDelayMin = 600;
            uint32 buyerDelayMax = 3600;
            float buyerCatalogRatio = 0.75f;
            float buyerVendorMultiplier[5] = { 0.0f, 2.0f, 3.0f, 5.0f, 8.0f };  // by quality, grey..epic
            uint32 buyerDailyBudget = 500;                  // gold per house
        };

        void LoadConfig();
        void LoadSellers();
        void RunHouse(House& house);
        void Restock(House& house, std::unordered_map<uint32, uint32>& counts);
        bool Post(House& house, CatalogItem const& entry);
        void Buy(House& house, std::vector<AuctionEntry const*> const& candidates);
        bool IsMarketListing(AuctionEntry const* auction) const;
        uint32 BuyerLimit(uint32 item, uint32 count, uint32 houseIndex) const;
        float GetFactor(uint32 item, uint32 houseIndex) const;
        void Adjust(House& house, uint32 item, bool sold);
        uint32 HouseIndex(House const& house) const { return uint32(&house - m_houses.data()); }

        Settings m_config;
        std::map<uint32, Tier> m_tiers;
        std::unordered_map<uint32, CatalogItem> m_catalog;
        std::vector<uint32> m_catalogOrder;                 // catalog item ids, in a fixed order
        std::vector<House> m_houses;
        std::unordered_map<uint64, float> m_factors;        // (item << 8 | house index) -> price drift
        std::vector<uint32> m_sellers[3];                   // alliance, horde, any
        std::unordered_set<uint32> m_sellerSet;
        time_t m_sellersLoadedAt = 0;
        uint32 m_timer = 0;
        uint32 m_nextHouse = 0;
        uint32 m_buyerDay = 0;
};

#define sAuctionMarket MaNGOS::Singleton<AuctionMarket>::Instance()

#endif
